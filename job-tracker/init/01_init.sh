CREATE USER ${APP_DB_USER} WITH
    PASSWORD        '${APP_DB_PASSWORD}'
    NOSUPERUSER
    NOCREATEDB
    NOCREATEROLE
    LOGIN
    CONNECTION LIMIT 40;

GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${APP_DB_USER};
GRANT USAGE   ON SCHEMA public           TO ${APP_DB_USER};

-- ── Table ────────────────────────────────────────────────────────────────────
CREATE TABLE job_execution (
    job_id           VARCHAR(30) NOT NULL,
    source           VARCHAR(20) NOT NULL,
    job_type         VARCHAR(30) NOT NULL,
    status           VARCHAR(10) NOT NULL,
    started_at       TIMESTAMP   NOT NULL,
    finished_at      TIMESTAMP       NULL,
    duration_seconds INT GENERATED ALWAYS AS (
        EXTRACT(EPOCH FROM (finished_at - started_at))::INT
    ) STORED,

    CONSTRAINT pk_job_execution
        PRIMARY KEY (job_id),

    CONSTRAINT chk_source
        CHECK (source IN ('x','instagram','tiktok','linkedin','youtube')),

    CONSTRAINT chk_job_type
        CHECK (job_type IN (
            'post_crawl','profile_crawl','video_metadata',
            'account_lookup','comment_crawl'
        )),

    CONSTRAINT chk_status
        CHECK (status IN ('SUCCESS','FAILED','RUNNING','QUEUED')),

    CONSTRAINT chk_finished_at
        CHECK (
            (status IN ('SUCCESS','FAILED') AND finished_at IS NOT NULL) OR
            (status IN ('RUNNING','QUEUED')  AND finished_at IS NULL)
        )
);

-- ── Indexes ──────────────────────────────────────────────────────────────────
-- Aggregation by composite key (GROUP BY in Metabase)
CREATE INDEX idx_job_exec_agg
    ON job_execution (source, job_type, status);

-- Date-range filtering
CREATE INDEX idx_job_exec_started
    ON job_execution (started_at DESC);

-- Partial index for active jobs only (small, fast)
CREATE INDEX idx_job_exec_active
    ON job_execution (started_at)
    WHERE status IN ('RUNNING','QUEUED');

-- ── Grant DML to app user ─────────────────────────────────────────────────────
GRANT SELECT, INSERT, UPDATE, DELETE ON job_execution TO ${APP_DB_USER};

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_DB_USER};

